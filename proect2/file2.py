a= int(input())
b = int(input())
c = input("что нужно сделать? введите знак +,-,*,/,**, или словами плюс, минус, умножить, разделить, в степень, степень только b \n")
if c == "+" or c == "плюс":
    print(a+b)
if c == "*" or c == "умножить":
    print(a*b)
if c == "/" or c == "разделить":
    print(a/b)
if c == "**" or c == "в степень":
    print(a**b)
if c == "-" or c == "минус":
    print(a-b)
